/*
Purpose: Insert the fixed product categories used by the synthetic dataset.
How to run: Execute after 01_create_tables.sql and before loading data CSVs.
Notes: Category IDs are explicit and match the category IDs generated by Python.
       The existence check makes this script safe to rerun.
*/

USE [OrderManagementSalesAnalytics];
GO

-- Keep category IDs stable so generated Products rows reference the right category.
SET IDENTITY_INSERT dbo.Categories ON;

INSERT INTO dbo.Categories (CategoryID, CategoryName, Description, IsActive)
SELECT v.CategoryID, v.CategoryName, v.Description, 1
FROM (VALUES
    (1, N'Electronics', N'Consumer electronics and accessories.'),
    (2, N'Home and Kitchen', N'Household and kitchen products.'),
    (3, N'Books', N'Printed books and learning materials.'),
    (4, N'Clothing', N'Apparel and everyday wear.'),
    (5, N'Sports', N'Sports and outdoor equipment.'),
    (6, N'Beauty', N'Personal care and beauty products.'),
    (7, N'Toys', N'Toys, games, and activities.'),
    (8, N'Office', N'Office and stationery supplies.')
) AS v (CategoryID, CategoryName, Description)
WHERE NOT EXISTS
(
    SELECT 1
    FROM dbo.Categories AS c
    WHERE c.CategoryID = v.CategoryID
       OR c.CategoryName = v.CategoryName
);

SET IDENTITY_INSERT dbo.Categories OFF;
GO

-- Verify all eight reference categories are present.
SELECT CategoryID, CategoryName
FROM dbo.Categories
ORDER BY CategoryID;
GO
